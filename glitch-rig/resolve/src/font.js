const SETS = {
  symbols: '!#$%&*+-=<>?@^~/\\|{}[]();:,.',
  letters: 'ABCDEFGHIJKLMNOPQRSTUVWXYZ',
  numbers: '0123456789',
  binary: '01',
  kana: 'アイウエオカキクコサシスセソタツテナノハミメモヤユラリルレロワン',
  code: '0123456789ABCDEF<>{}[]();=+-*/#$&!?',
  blocks: '░▒▓█▀▄▌▐■□▪◆◇●○',
  ascii: " .`':-~=+*xo#%&@",
};
const SET_ORDER = ['symbols', 'letters', 'numbers', 'binary', 'kana', 'code', 'blocks', 'ascii'];

function bits(ch) {
  const rows = G[ch].split('|');
  if (rows.length !== 7 || rows.some((r) => r.length !== 5)) throw new Error('bad glyph ' + ch);
  let lo = 0, hi = 0;
  rows.forEach((r, ri) => {
    for (let c = 0; c < 5; c++) {
      if (r[c] !== '#') continue;
      if (ri < 4) lo |= 1 << (ri * 5 + c);
      else hi |= 1 << ((ri - 4) * 5 + c);
    }
  });
  return [lo, hi];
}
const ink = (ch) => (G[ch].match(/#/g) || []).length;

// Every glyph once, then each set as a list of global indices sorted by ink.
function build() {
  const all = Object.keys(G);
  const index = new Map(all.map((ch, i) => [ch, i]));
  const sets = SET_ORDER.map((name) => {
    const chars = Array.from(SETS[name]);
    chars.forEach((ch) => { if (!index.has(ch)) throw new Error('missing glyph ' + JSON.stringify(ch)); });
    return chars.map((ch) => index.get(ch)).sort((a, b) => ink(all[a]) - ink(all[b]));
  });
  return { all, index, sets, bits: all.map(bits) };
}

// DCTL: glyph bitmaps and set lookup as switch functions.
function dctl() {
  const f = build();
  const lo = f.bits.map(([l], i) => `    case ${i}: return ${l};`).join('\n');
  const hi = f.bits.map(([, h], i) => `    case ${i}: return ${h};`).join('\n');
  const setCases = f.sets.map((s, si) =>
    `    case ${si}: { int n = ${s.length}; int k = ((i % n) + n) % n;\n      switch (k) { ${s.map((g, k) => `case ${k}: return ${g};`).join(' ')} } return 0; }`).join('\n');
  const counts = f.sets.map((s, si) => `    case ${si}: return ${s.length};`).join('\n');
  return `
__DEVICE__ int gr_glyphLo(int g) {
  switch (g) {
${lo}
  }
  return 0;
}
__DEVICE__ int gr_glyphHi(int g) {
  switch (g) {
${hi}
  }
  return 0;
}
// index i of character set s (0 symbols .. 7 ascii), densest last
__DEVICE__ int gr_setGlyph(int s, int i) {
  switch (s) {
${setCases}
  }
  return 0;
}
__DEVICE__ int gr_setCount(int s) {
  switch (s) {
${counts}
  }
  return 1;
}
`;
}

// Text -> global glyph indices for WORDS (unknown characters become spaces).
function wordIndices(text) {
  const f = build();
  return Array.from(String(text || '').toUpperCase()).map((ch) => (f.index.has(ch) ? f.index.get(ch) : f.index.get(' ')));
}

module.exports = { build, dctl, wordIndices, SET_ORDER, G };
